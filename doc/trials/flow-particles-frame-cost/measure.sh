#!/bin/bash
# measure.sh — one run of the flow-particles frame-cost trial.
#
# For each host, arm and particle count it launches the widget gallery on a
# headless host through the scene runner, selects the `flowbench` demo, clicks
# the count and the arm, waits for the demo's window of frames to complete, and
# keeps what came back: the demo's own summary (the Go side of the layer, the
# host's opcode dispatch, the bytes written) from the runner's stdout, and the
# host's raster statistics (tessellate, rasterise) from its log. One launch per
# cell, because the host's raster statistics are cumulative over a launch.
#
# Usage:
#   doc/trials/flow-particles-frame-cost/measure.sh <run-dir>
#
# Environment:
#   HOSTS    hosts to measure         (default: "cpu wgpu")
#   ARMS     paint arms               (default: all three)
#   COUNTS   particle counts          (default: "1000 2500 5000 10000 20000")
#   REPEATS  launches per cell        (default: 1)
#
# Prerequisites: both headless hosts built from the tree under test —
#   rust/imzero2/build_rust_headless_soft.sh   (cpu)
#   rust/imzero2/build_rust_headless.sh        (wgpu)
# and an otherwise idle machine. The protocol is in README.md.
set -euo pipefail
here=$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")
root=$(cd "$here/../../.." && pwd)
run=${1:?usage: measure.sh <run-dir>}
mkdir -p "$run/raw"
run=$(cd "$run" && pwd)

HOSTS=${HOSTS:-"cpu wgpu"}
ARMS=${ARMS:-"segments-mesh segments-tessellated line-per-segment"}
COUNTS=${COUNTS:-"1000 2500 5000 10000 20000"}
REPEATS=${REPEATS:-1}

client() {
	case "$1" in
	cpu) echo "$root/rust/imzero2/target/headless-soft/release/imzero2" ;;
	wgpu) echo "$root/rust/imzero2/target/headless/release/imzero2" ;;
	*) echo "unknown host $1" >&2; exit 2 ;;
	esac
}

work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT

# scene <file> <count> <arm>: the scene document of one cell.
scene() {
	cat >"$1" <<SCENE
---
type: reference
audience: contributor
status: draft
scene:
  launch: widgets
  size: 1100x900
  stepSettleMs: 350
  env: {IMZERO2_HEADLESS_RASTER_STATS: "1"}
---

> **Status: draft — pre-human-review.** Generated by the flow-particles trial.

# flowbench cell

$3 at $2 particles.

\`\`\`jsonl trace
{"do":"wait","role":"text_input"}
{"do":"sleep","settleMs":200}
{"do":"focus","role":"text_input"}
{"do":"type","role":"text_input","text":"flow bench"}
{"do":"wait","contains":"flow bench","settleMs":400}
{"do":"click","contains":"flow bench"}
{"do":"click","name":"$3","role":"button"}
{"do":"click","name":"n=$2","role":"button"}
{"do":"read","valueContains":"bench done","role":"label","pattern":"bench done arm=$3 particles=$2 segments=(?P<segments>\\\\d+)"}
{"do":"sleep","settleMs":2500}
{"do":"tree","text":"bench ","role":"label"}
\`\`\`
SCENE
}

field() { sed -n "s/.*[ \"]$1=\"\{0,1\}\([0-9a-z-]*\).*/\1/p" | tail -1; }

out="$run/results.tsv"
printf 'host\tarm\tparticles\trepeat\tsegments\tgo_draw_p50_us\tgo_draw_p95_us\tinterpret_p50_us\tinterpret_p95_us\twritten_p50_bytes\traster_p50_us\traster_p90_us\ttess_p50_us\traster_frames\ttris\n' >"$out"

cell() { # host arm count repeat
	local host=$1 arm=$2 count=$3 rep=$4 name="$1-$2-$3-$4"
	scene "$work/$name.scene.md" "$count" "$arm"
	rm -rf "$work/out"
	if ! "$root/scripts/dev/scene.sh" --out "$work/out" --timeout 10m --clientBinary "$(client "$host")" \
		"$work/$name.scene.md" >"$work/stdout" 2>"$work/stderr"; then
		echo "FAILED $name" >&2
		sed 's/\x1b\[[0-9;]*m//g' "$work/stdout" | tail -20 >"$run/raw/$name.failed.txt"
		return 0
	fi
	{
		sed 's/\x1b\[[0-9;]*m//g' "$work/stdout" | grep -a '^ *label ="bench ' | sed 's/ #[0-9]* @.*//'
		sed 's/\x1b\[[0-9;]*m//g' "$work/out/logs/$name.host.log" | grep -a 'raster stats' | tail -1 |
			sed 's/^[^ ]* *INFO [^:]*: [^:]*:[0-9]*: //; s/ run_id="[^"]*"//'
	} >"$run/raw/$name.txt"
	local raw="$run/raw/$name.txt"
	printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$host" "$arm" "$count" "$rep" \
		"$(field segments <"$raw")" "$(field draw_p50_us <"$raw")" "$(field draw_p95_us <"$raw")" \
		"$(field interpret_p50_us <"$raw")" "$(field interpret_p95_us <"$raw")" "$(field written_p50_bytes <"$raw")" \
		"$(field p50_us <"$raw")" "$(field p90_us <"$raw")" "$(field tess_p50_us <"$raw")" \
		"$(field frames <"$raw")" "$(field tris <"$raw")" >>"$out"
	tail -1 "$out"
}

for host in $HOSTS; do
	for rep in $(seq 1 "$REPEATS"); do
		# The floor: the same frame with no layer on it.
		cell "$host" segments-mesh 0 "$rep"
		for arm in $ARMS; do
			for count in $COUNTS; do
				cell "$host" "$arm" "$count" "$rep"
			done
		done
	done
done
echo "results: $out"
