#!/bin/bash
# measure.sh — one run of the image upload-cost trial.
#
# For each host, arm and side it launches the widget gallery on a headless
# host through the scene runner, selects the `imagebench` demo, clicks the arm
# and then the side, waits for the demo's window of frames to complete, and
# keeps what came back: the demo's own summary (the Go side of the image, the
# whole frame's render / sync / total, the host's opcode dispatch, the bytes
# written, the cycle period) from the runner's stdout, and the host's raster
# statistics from its log. One launch per cell, because the host's raster
# statistics are cumulative over a launch and because a cell must not inherit
# another's textures. The script is the portolan land trial's, with sides in
# place of views, and two differences: the scene runner is built once, at the
# start, so every cell of a run measures the same Go build even when the tree
# moves underneath; and a run resumes — a cell whose raw file exists is
# skipped, so a matrix can be run in pieces.
#
# Usage:
#   doc/trials/image-upload-cost/measure.sh <run-dir>
#
# Environment:
#   HOSTS    hosts to measure         (default: "cpu wgpu")
#   ARMS     upload arms              (default: "off resident reupload tiles512 tiles256")
#   SIDES    image sides              (default: "s512 s1024 s2048 s4096 s8192")
#   REPEATS  launches per cell        (default: 1)
#   FPS      the host's frame cadence (default: 240) — the floor under the
#            period column; 240 is the host's maximum
#   CLIENT_ROOT  checkout whose rust/imzero2/target holds the headless
#            clients (default: this one) — for a run from a worktree
#
# Prerequisites: both headless hosts built from the tree under test —
#   rust/imzero2/build_rust_headless_soft.sh   (cpu)
#   rust/imzero2/build_rust_headless.sh        (wgpu)
# and an otherwise idle machine. The protocol is in README.md.
set -euo pipefail
here=$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")
root=$(cd "$here/../../.." && pwd)
run=${1:?usage: measure.sh <run-dir>}
mkdir -p "$run/raw"
run=$(cd "$run" && pwd)

HOSTS=${HOSTS:-"cpu wgpu"}
ARMS=${ARMS:-"off resident reupload tiles512 tiles256"}
SIDES=${SIDES:-"s512 s1024 s2048 s4096 s8192"}
REPEATS=${REPEATS:-1}
FPS=${FPS:-240}
CLIENT_ROOT=${CLIENT_ROOT:-$root}

client() {
	case "$1" in
	cpu) echo "$CLIENT_ROOT/rust/imzero2/target/headless-soft/release/imzero2" ;;
	wgpu) echo "$CLIENT_ROOT/rust/imzero2/target/headless/release/imzero2" ;;
	*) echo "unknown host $1" >&2; exit 2 ;;
	esac
}

work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT

# The scene runner is the imzero2 host binary (ADR-0248 §SD4); scripts/dev/
# scene.sh builds it on every call, which would let the tree under test change
# between two cells.
# shellcheck source=/dev/null
source "$root/scripts/dev/go-build-env.sh"
runner="$work/imzero2-scene"
# shellcheck disable=SC2086 # deliberate word splitting of the flag list
(cd "$root" && CGO_ENABLED=0 go build $BOXER_GO_FLAGS -tags "${BOXER_GO_TAGS:+$BOXER_GO_TAGS,}binary_log" \
	-o "$runner" ./public/thestack/cmd/imzero2/)

# scene <file> <side> <arm>: the scene document of one cell.
scene() {
	cat >"$1" <<SCENE
---
type: reference
audience: contributor
status: draft
scene:
  launch: widgets
  size: 1100x900
  fps: ${FPS}
  stepSettleMs: 350
  env: {IMZERO2_HEADLESS_RASTER_STATS: "1"}
---

> **Status: draft — pre-human-review.** Generated by the image upload-cost trial.

# imagebench cell

$3 at $2.

\`\`\`jsonl trace
{"do":"wait","role":"text_input"}
{"do":"sleep","settleMs":200}
{"do":"focus","role":"text_input"}
{"do":"type","role":"text_input","text":"image bench"}
{"do":"wait","contains":"image bench","settleMs":400}
{"do":"click","contains":"image bench"}
{"do":"click","name":"$3","role":"button"}
{"do":"click","name":"$2","role":"button"}
{"do":"read","valueContains":"bench done","role":"label","pattern":"bench done arm=$3 side=$2 tiles=(?P<tiles>\\\\d+)"}
{"do":"sleep","settleMs":2500}
{"do":"tree","text":"bench ","role":"label"}
\`\`\`
SCENE
}

field() { sed -n "s/.*[ \"]$1=\"\{0,1\}\([0-9a-z-]*\).*/\1/p" | tail -1; }

cols="tiles payload_bytes frames emit_p50_us emit_p95_us render_p50_us sync_p50_us total_p50_us total_p95_us interpret_p50_us interpret_p95_us written_p50_bytes period_p50_us period_p95_us first_total_us first_interpret_us first_period_us"
out="$run/results.tsv"
[ -s "$out" ] || {
	printf 'host\tarm\tside\trepeat'
	for col in $cols; do printf '\t%s' "$col"; done
	printf '\traster_p50_us\traster_p90_us\ttess_p50_us\traster_frames\n'
} >"$out"

cell() { # host arm side repeat
	local host=$1 arm=$2 side=$3 rep=$4 name="$1-$2-$3-$4"
	[ -e "$run/raw/$name.txt" ] && return 0
	rm -f "$run/raw/$name.failed.txt"
	scene "$work/$name.scene.md" "$side" "$arm"
	rm -rf "$work/out"
	if ! "$runner" --logFormat=console --logLevel=warn imzero2 scene --repoRoot "$root" \
		--out "$work/out" --timeout 15m --clientBinary "$(client "$host")" \
		"$work/$name.scene.md" >"$work/stdout" 2>"$work/stderr"; then
		echo "FAILED $name" >&2
		{
			sed 's/\x1b\[[0-9;]*m//g' "$work/stdout" | tail -20
			echo "--- stderr"
			sed 's/\x1b\[[0-9;]*m//g' "$work/stderr" | tail -20
			echo "--- host log"
			sed 's/\x1b\[[0-9;]*m//g' "$work/out/logs/$name.host.log" 2>/dev/null | grep -a -i -E 'error|warn|panic|exceeds|refus' | tail -20
		} >"$run/raw/$name.failed.txt"
		return 0
	fi
	{
		sed 's/\x1b\[[0-9;]*m//g' "$work/stdout" | grep -a '^ *label ="bench ' | sed 's/ #[0-9]* @.*//'
		sed 's/\x1b\[[0-9;]*m//g' "$work/out/logs/$name.host.log" | grep -a 'raster stats' | tail -1 |
			sed 's/^[^ ]* *INFO [^:]*: [^:]*:[0-9]*: //; s/ run_id="[^"]*"//'
		sed 's/\x1b\[[0-9;]*m//g' "$work/out/logs/$name.host.log" | grep -a -i -E 'exceeds max_texture_side|refus' | sort | uniq -c | tail -3 || true
	} >"$run/raw/$name.txt"
	local raw="$run/raw/$name.txt"
	{
		printf '%s\t%s\t%s\t%s' "$host" "$arm" "$side" "$rep"
		# The demo's labels and the host's statistics share field names
		# (frames), so each is read from its own lines.
		for col in $cols; do printf '\t%s' "$(grep -a 'label =' "$raw" | field "$col")"; done
		for col in p50_us p90_us tess_p50_us frames; do printf '\t%s' "$(grep -a 'raster stats' "$raw" | field "$col")"; done
		printf '\n'
	} >>"$out"
	tail -1 "$out"
}

for host in $HOSTS; do
	for rep in $(seq 1 "$REPEATS"); do
		for side in $SIDES; do
			for arm in $ARMS; do
				cell "$host" "$arm" "$side" "$rep"
			done
		done
	done
done
echo "results: $out"
