// probeSql is every statement the probe composes, for every case kind,
// over fixed times: the golden a mart rename must break.
func probeSql(t *testing.T) string {
	m, err := loadMarts(factsschema.DatabaseName)
	require.NoError(t, err)
	from := time.Date(2026, 10, 31, 12, 0, 0, 0, time.UTC)
	to := from.Add(time.Hour)
	b := strings.Builder{}
	b.WriteString("-- Generated by TestProbeSqlGolden -update. DO NOT EDIT.\n")
	section := func(name, sql string) {
		b.WriteString("\n-- " + name + "\n" + sql + ";\n")
	}
	for _, c := range fixtureCases {
		require.NoError(t, c.validate(), c.String())
		q := listQuery{Case: c, From: from, To: to, Limit: 2000}
		section("list "+c.Kind.String(), m.listSQL(q))
	}
	f := Filter{}.with(FacetKind, "auditEvent", false).with(FacetStatus, "ok", true).
		with(FacetDomainAction, "trail.config", false).with(FacetPrincipal, "p-1", true).with(FacetApp, "apps/x", false)
	q := listQuery{Case: Case{Kind: CaseRun, Value: "run-1"}, From: from, To: to, Filter: f, Limit: 2000,
		Cursor: &Cursor{TsNs: from.Add(30 * time.Minute).UnixNano(), Id: 99}}
	section("list filtered with a cursor", m.listSQL(q))
	section("strip by kind", m.stripSQL(q, time.Minute, StripByKind))
	section("strip by status", m.stripSQL(q, time.Minute, StripByStatus))
	for _, facet := range AllFacets {
		section("facet "+facet.String(), m.facetSQL(facet, Case{Kind: CaseConversation, Value: "conv-1"}, from, to))
	}
	section("audit by ids", m.auditByIdsSQL([]uint64{3, 5}, from, to))
	r := &Row{Id: 5, TsNs: from.Add(10 * time.Minute).UnixNano(), Run: "run-1", Task: "task-1"}
	section("context before", m.contextSQL(r, false, 30*24*time.Hour))
	section("context after", m.contextSQL(r, true, 30*24*time.Hour))
	a := &AuditDetail{Id: 5, TsNs: r.TsNs, Domain: "llm-ration", Entity: "rule:r-1", Run: "run-1"}
	section("previous audit", m.previousAuditSQL(a, 30*24*time.Hour))
	section("gaps", m.gapsSQL("run-1", from, to))
	section("grant pair", m.grantPairSQL(r, 30*24*time.Hour))
	// The exception rules (ADR-0350 §SD7): each SQL rule over the filtered
	// read with a cursor and a lower bound, the statement that unions them,
	// the reviews of the read's rows, and the entity's state as of a bound.
	look := 30 * 24 * time.Hour
	lower := &Cursor{TsNs: from.Add(5 * time.Minute).UnixNano(), Id: 11}
	for _, rule := range Rules {
		if !rule.FromHeld() {
			section("rule "+rule.Name, m.ruleSQL(rule, q, lower, look))
		}
	}
	section("exceptions", m.exceptionsSQL(q, lower, look))
	section("reviews", m.reviewsSQL(q, lower))
	section("as of", m.asOfSQL("rule:r-1", to, look))
	// The analytic views (ADR-0350 §SD11): the matrix over the timeline and
	// over the audit-event mart, each under the filter; the dotted chart by
	// a timeline row and by entity, at the strip's bucket size.
	section("matrix app × operation", m.matrixSQL(q, ActorApp, ObjectOperation))
	section("matrix window × operation, no filter", m.matrixSQL(listQuery{Case: q.Case, From: from, To: to}, ActorWindow, ObjectOperation))
	section("matrix principal × entity", m.matrixSQL(q, ActorPrincipal, ObjectEntity))
	section("matrix app × subject, no filter", m.matrixSQL(listQuery{Case: q.Case, From: from, To: to}, ActorApp, ObjectSubject))
	section("dotted by window", m.dottedSQL(q, DottedWindow, time.Minute))
	section("dotted by conversation", m.dottedSQL(listQuery{Case: Case{Kind: CaseConversation, Value: "conv-1"}, From: from, To: to}, DottedConversation, time.Minute))
	section("dotted by entity", m.dottedSQL(q, DottedEntity, time.Minute))
	// M5: the day × hour grid in the picker's zone, and the numeric series
	// under each statistic, at the strip's bucket size.
	section("day × hour in Europe/Berlin", m.dayHourSQL(q, "Europe/Berlin"))
	section("day × hour in UTC, no filter", m.dayHourSQL(listQuery{Case: Case{Kind: CaseAll}, From: from, To: to}, "UTC"))
	section("series rows", m.seriesSQL(q, seriesPick{Measure: MeasureRows}, time.Minute))
	section("series tokens-in sum", m.seriesSQL(q, seriesPick{Measure: MeasureTokensIn, Stat: StatSum}, time.Minute))
	section("series tokens-out p50", m.seriesSQL(q, seriesPick{Measure: MeasureTokensOut, Stat: StatP50}, time.Minute))
	section("series elapsed-ms p95", m.seriesSQL(q, seriesPick{Measure: MeasureElapsedMs, Stat: StatP95}, time.Minute))
	section("series elapsed-ms max, no filter", m.seriesSQL(listQuery{Case: q.Case, From: from, To: to}, seriesPick{Measure: MeasureElapsedMs, Stat: StatMax}, 5*time.Minute))
	return b.String()
}

// The statements the probe sends are pinned: a mart rename, a column
// moved, or a case read differently changes this file and fails here.
func TestProbeSqlGolden(t *testing.T) {
	got := probeSql(t)
	if *updateGolden {
		require.NoError(t, os.MkdirAll("testdata", 0o755))
		require.NoError(t, os.WriteFile(probeGolden, []byte(got), 0o644))
	}
	want, err := os.ReadFile(probeGolden)
	require.NoError(t, err, "run go test -run TestProbeSqlGolden -update in this package")
	require.Equal(t, string(want), got, "run go test -run TestProbeSqlGolden -update in this package")
}

// The physical names come from the composer, never spelled here; every
// statement reads only the views the composer makes.
func TestProbeReadsByThePhysicalNamesTheComposerMints(t *testing.T) {
	m, err := loadMarts(factsschema.DatabaseName)
	require.NoError(t, err)
	tl := m.views[trailviews.ViewTimeline]
	for _, n := range timelineNames {
		assert.Contains(t, m.col(trailviews.ViewTimeline, n), `"`, n)
	}
	found := false
	for _, c := range tl.Columns {
		if c.Name == "headline" {
			found = true
			assert.Equal(t, `"`+c.Physical+`"`, m.col(trailviews.ViewTimeline, "headline"))
		}
	}
	assert.True(t, found)
	assert.Panics(t, func() { m.col(trailviews.ViewTimeline, "no-such-column") })
	sql := m.listSQL(listQuery{Case: Case{Kind: CaseSubject, Value: "77"}, From: time.Unix(0, 0), To: time.Unix(60, 0), Limit: 10})
	assert.Contains(t, sql, factsschema.DatabaseName+"."+trailviews.ViewAuditEvents, "the subject case reads the audit events' ids")
	assert.True(t, strings.HasSuffix(sql, "LIMIT 10"), "bounded by the cap")
}

// A literal cannot break out of its quotes, and the local quoter agrees
// with jackstay.QuoteString, which it copies.
func TestSqlStringEscapes(t *testing.T) {
	assert.Equal(t, `'a\'b\\c'`, sqlString(`a'b\c`))
	for _, v := range []string{"", "plain", `a'b\c`, `\'`, "''", "ä'ö\\", "new\nline", "\x00"} {
		assert.Equal(t, jackstay.QuoteString(v), sqlString(v), "%q", v)
	}
}

func TestStepForKeepsTheBucketsUnderTheCount(t *testing.T) {
	for _, span := range []time.Duration{time.Minute, time.Hour, 24 * time.Hour, 30 * 24 * time.Hour, 400 * 24 * time.Hour} {
		for _, n := range []int{60, 90, 120} {
			step := stepFor(span, n)
			assert.LessOrEqual(t, int(span/step), n, "%s / %d", span, n)
		}
	}
	assert.Equal(t, time.Minute, stepFor(time.Hour, 90))
	assert.Equal(t, 60, stripBuckets(100))
	assert.Equal(t, 120, stripBuckets(5000))
	assert.Equal(t, 100, stripBuckets(800))
}
