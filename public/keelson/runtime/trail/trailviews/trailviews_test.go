// goldenPath is the composed views for the default database, checked in so
// an operator can install them without building anything:
// `clickhouse-client --multiquery < trailviews_clickhouse.out.sql`.
const goldenPath = "trailviews_clickhouse.out.sql"

func goldenSql(t *testing.T) string {
	stmts, err := Statements("", "")
	require.NoError(t, err)
	return "-- Code generated by TestGenerateViewsSql. DO NOT EDIT.\n\n" + strings.Join(stmts, ";\n\n") + ";\n"
}

// TestGenerateViewsSql (re)writes the golden file; run it after changing a
// view, the vocabulary or the trail schema.
func TestGenerateViewsSql(t *testing.T) {
	require.NoError(t, os.WriteFile(goldenPath, []byte(goldenSql(t)), 0o644))
}

// The checked-in file is what Compose emits now: a view changed without
// regenerating fails here, not on an operator's server.
func TestGoldenIsCurrent(t *testing.T) {
	have, err := os.ReadFile(goldenPath)
	require.NoError(t, err)
	require.Equal(t, goldenSql(t), string(have), "run go generate in this package")
}

var aggregates = map[string]bool{ViewActionOutcomes: true, ViewConversations: true, ViewTasks: true}

func TestComposeShape(t *testing.T) {
	views, err := Compose("", "")
	require.NoError(t, err)
	names := make([]string, 0, len(views))
	stamp := "\nCOMMENT " + Stamp().Literal()
	for _, v := range views {
		names = append(names, v.Name)
		require.True(t, strings.HasPrefix(v.Sql, "CREATE OR REPLACE VIEW boxer."+v.Name+" AS\n"), v.Name)
		require.True(t, strings.HasSuffix(v.Sql, stamp), "every view is stamped: %s", v.Name)
		// No semicolon anywhere: a naive statement splitter (chstore's
		// splitOnSemicolon is one) must not be able to cut a view apart.
		require.NotContains(t, v.Sql, ";", v.Name)
		// Everything authored has been expanded: no client-side sugar, no
		// handle and no placeholder survives into what the server stores.
		for _, sugar := range []string{"LW_GET", "LW_PLAIN", "`", "{"} {
			require.NotContains(t, v.Sql, sugar, v.Name)
		}
	}
	require.Equal(t, []string{
		ViewModelCalls, ViewModelMessages, ViewAgentActions, ViewAgentGrants,
		ViewAgentCaptures, ViewAgentDisclosures, ViewHttpFetches, ViewAdhocBundles, ViewAuditEvents,
		ViewTimeline, ViewActionOutcomes, ViewConversations, ViewTasks,
	}, names, "creation order: each view only reads views created before it")
	require.Equal(t, names, AllViewNames())

	general := map[string]bool{ViewTimeline: true, ViewHttpFetches: true, ViewAdhocBundles: true, ViewAuditEvents: true}
	for _, n := range names {
		// The class prefix says what a reader may rely on (ADR-0051).
		if aggregates[n] {
			require.True(t, strings.HasPrefix(n, "agg_trail_"), n)
		} else {
			require.True(t, strings.HasPrefix(n, "dm_trail_"), n)
		}
		// The agentic tag is in the name of every view over what agents
		// and models write, and in no other: the trail itself is general.
		require.Equal(t, !general[n], strings.Contains(n, "_trail_"+agenticTag+"_"), n)
	}

	// Each per-kind data mart keeps its kind test as a literal has(), the
	// term the skip index prunes on.
	for i, kv := range kindViews {
		require.Contains(t, views[i].Sql, "has(\"tv:symbol:lr:", kv.name)
		require.Contains(t, views[i].Sql, ", "+strconv.FormatUint(kv.kind.GetId().Value(), 10)+")", kv.name)
	}
}

// Every view is a leeway table: a data mart carries the facts backbone,
// an aggregate names its lineage, and every other column is an opaque
// plain column minted exactly as LW_PLAIN mints it, under a name that is
// unique within its view.
func TestColumnsAreLeeway(t *testing.T) {
	views, err := Compose("", "")
	require.NoError(t, err)
	composer, err := lwsql.NewComposer(lwsql.DefaultTableSegments())
	require.NoError(t, err)
	for _, v := range views {
		seen := map[string]bool{}
		backboneSeen := 0
		for _, c := range v.Columns {
			require.False(t, seen[c.Name], "%s: %s twice", v.Name, c.Name)
			seen[c.Name] = true
			require.Contains(t, v.Sql, `"`+c.Physical+`"`, "%s selects %s", v.Name, c.Name)
			if c.Backbone {
				backboneSeen++
				continue
			}
			want, merr := composer.PlainColumn(c.Name, c.CanonicalType, []string{mintItem})
			require.NoError(t, merr)
			require.Equal(t, want, c.Physical, "%s.%s", v.Name, c.Name)
			require.True(t, strings.HasPrefix(c.Physical, "oq:"+c.Name+":"+c.CanonicalType+":"), c.Physical)
		}
		if aggregates[v.Name] {
			require.Zero(t, backboneSeen, "an aggregate's rows are not facts rows: %s", v.Name)
			require.True(t, seen["facts-ids"], "an aggregate names its lineage: %s", v.Name)
		} else {
			require.Equal(t, len(backbone), backboneSeen, "a data mart is keyed by the facts id: %s", v.Name)
		}
	}
}

func TestComposeOtherTable(t *testing.T) {
	views, err := Compose("audit", "trail_facts")
	require.NoError(t, err)
	for i, v := range views {
		require.NotContains(t, v.Sql, "boxer.", v.Name)
		require.True(t, strings.HasPrefix(v.Sql, "CREATE OR REPLACE VIEW audit."+v.Name+" AS\n"), v.Name)
		if i < len(kindViews) {
			require.Contains(t, v.Sql, "FROM audit.trail_facts\n", v.Name)
		}
	}
}

