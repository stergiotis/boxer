// Every membership a view reads is one the runtime vocabulary registers:
// the lookup is what turns the authored names into ids, and a retired or
// misspelled one must fail composition rather than read empty.
func TestMembershipsResolve(t *testing.T) {
	for _, kv := range kindViews {
		for _, c := range append(append(append([]column{}, contextColumns...), causeColumns...), kv.columns...) {
			id, err := membershipIds{}.LookupMembership(membName(c.memb))
			require.NoError(t, err, c.name)
			require.Equal(t, c.memb.GetId().Value(), id, c.name)
		}
	}
	_, err := membershipIds{}.LookupMembership("agentActionTask")
	require.Error(t, err, "a retired per-kind spelling is not in the vocabulary")
}
