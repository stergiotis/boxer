//go:build ignore

// gen_chaliases.go regenerates chaliases_gen.go from the local
// clickhouse binary's own system.functions — run it via
// `go generate ./public/keelson/runtime/help/search` after bumping the
// engine pin. The alias set is a property of the engine version, which
// is exactly why it can be a generated table rather than a runtime
// round-trip (ADR-0164 §SD7): searches work offline and inside the
// pure docsearch expansion pass, and drift is owned by the pin bump.
//
// Pairs differing only by case are dropped — the battery is
// case-insensitive, so `AIClassify → aiClassify` would inflate
// patterns without ever changing a match.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"sort"
	"strings"
)

func main() {
	version := query("SELECT version()")
	rows := query("SELECT name, alias_to FROM system.functions WHERE alias_to != '' ORDER BY name FORMAT TSV")

	type pair struct{ alias, canonical string }
	pairs := make([]pair, 0, 256)
	for line := range strings.SplitSeq(strings.TrimSpace(rows), "\n") {
		alias, canonical, ok := strings.Cut(line, "\t")
		if !ok || strings.EqualFold(alias, canonical) {
			continue
		}
		pairs = append(pairs, pair{alias: alias, canonical: canonical})
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i].alias < pairs[j].alias })

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by gen_chaliases.go; DO NOT EDIT.
// Source: clickhouse local, system.functions, version %s.
// Regenerate after an engine pin bump: go generate ./public/keelson/runtime/help/search

package search

// chFunctionAliases maps a function alias to its canonical name
// (case-only pairs pre-filtered; the battery is case-insensitive).
var chFunctionAliases = map[string]string{
`, strings.TrimSpace(version))
	for _, p := range pairs {
		fmt.Fprintf(&b, "\t%q: %q,\n", p.alias, p.canonical)
	}
	b.WriteString("}\n")

	if err := os.WriteFile("chaliases_gen.go", b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen_chaliases:", err)
		os.Exit(1)
	}
	fmt.Printf("chaliases_gen.go: %d aliases (clickhouse %s)\n", len(pairs), strings.TrimSpace(version))
}

func query(sql string) string {
	out, err := exec.Command("clickhouse", "local", "--query", sql).Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen_chaliases: clickhouse local:", err)
		os.Exit(1)
	}
	return string(out)
}
