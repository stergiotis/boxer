package scene

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/stergiotis/boxer/public/observability/eh"
	"github.com/stergiotis/boxer/public/observability/eh/eb"
)

// StatusE is how one scene ended.
type StatusE string

const (
	// StatusPass: every step ran and every capture the trace names exists.
	StatusPass StatusE = "pass"
	// StatusFail: a step failed, or a capture is missing.
	StatusFail StatusE = "fail"
	// StatusSkip: a precondition did not hold. Not evidence either way.
	StatusSkip StatusE = "skip"
)

// Result is one scene's outcome.
type Result struct {
	Doc      *Doc
	Status   StatusE
	Reason   string
	Err      error
	Duration time.Duration
	// Captures are the PNGs the run wrote, relative to the output directory.
	Captures []string
	// Sidecars are the files its captures wrote beside them, the same way.
	Sidecars []string
}

// CollectDocs expands paths into scene documents: a file is itself, a
// directory is its *.scene.md files in name order — which is what makes a
// directory a tour.
func CollectDocs(paths []string) (docs []*Doc, err error) {
	for _, p := range paths {
		st, e := os.Stat(p)
		if e != nil {
			return nil, eb.Build().Str("path", p).Errorf("unable to read the scene path: %w", e)
		}
		files := []string{p}
		if st.IsDir() {
			if files, err = filepath.Glob(filepath.Join(p, "*"+DocSuffix)); err != nil {
				return nil, eh.Errorf("unable to list the scene directory: %w", err)
			}
			sort.Strings(files)
		}
		for _, f := range files {
			src, e := os.ReadFile(f)
			if e != nil {
				return nil, eb.Build().Str("path", f).Errorf("unable to read the scene document: %w", e)
			}
			doc, e := ParseDoc(f, src)
			if e != nil {
				return nil, e
			}
			docs = append(docs, doc)
		}
	}
	return docs, nil
}

// RunDoc runs one scene document from launch to teardown.
func RunDoc(doc *Doc, opts Options) (res Result) {
	start := time.Now()
	res = Result{Doc: doc, Status: StatusFail}
	defer func() { res.Duration = time.Since(start) }()

	for _, name := range doc.Spec.Requires {
		unmet, err := CheckRequire(name)
		if err != nil {
			res.Err = err
			return res
		}
		if unmet != "" && !opts.IgnoreRequires {
			res.Status, res.Reason = StatusSkip, unmet
			return res
		}
		if unmet != "" {
			res.Reason = "ran although " + unmet
		}
	}

	spec := doc.Spec
	if len(doc.Captures()) > 0 && !opts.DryRun {
		spec.Needs = append(append([]string(nil), spec.Needs...), NeedRaster)
	}
	opts.Name = doc.Name
	if spec.StepSettleMs > 0 {
		opts.SettleMs = spec.StepSettleMs
	}
	opts.SQL = doc.SQL
	// Stale captures of the same name would let a run that wrote nothing pass.
	for _, f := range doc.CaptureFiles() {
		_ = os.Remove(filepath.Join(opts.OutDir, f.PNG))
		for _, sc := range f.Sidecars {
			_ = os.Remove(filepath.Join(opts.OutDir, sc))
		}
	}

	s, err := Launch(spec, opts)
	if err != nil {
		res.Err = err
		return res
	}
	defer func() { _ = s.Close() }()

	if res.Err = s.Run(doc.Steps); res.Err != nil {
		return res
	}
	if !opts.DryRun {
		for _, f := range doc.CaptureFiles() {
			if !nonEmptyFile(filepath.Join(opts.OutDir, f.PNG)) {
				res.Err = eb.Build().Str("capture", f.PNG).Errorf("the trace ran but its capture was not written")
				return res
			}
			res.Captures = append(res.Captures, f.PNG)
			for _, sc := range f.Sidecars {
				if !nonEmptyFile(filepath.Join(opts.OutDir, sc)) {
					res.Err = eb.Build().Str("sidecar", sc).Errorf("the trace ran but a capture sidecar was not written")
					return res
				}
				res.Sidecars = append(res.Sidecars, sc)
			}
		}
	}
	res.Status = StatusPass
	return res
}

func nonEmptyFile(path string) bool {
	st, err := os.Stat(path)
	return err == nil && st.Size() > 0
}

// WriteIndex writes the gallery: each scene's prose, captures, query and
// trace. It is the scene documents read back with their pictures in.
func WriteIndex(outDir string, results []Result) (err error) {
	var b strings.Builder
	b.WriteString("# Scenes\n\nGenerated by `imzero2 scene` (ADR-0248) — " +
		time.Now().Format(time.RFC3339) + ".\n")
	for _, r := range results {
		b.WriteString("\n## " + r.Doc.Name + " — " + string(r.Status) + "\n\n")
		if r.Reason != "" {
			b.WriteString("_" + r.Reason + "_\n\n")
		}
		if r.Err != nil {
			b.WriteString("```\n" + PlainError(r.Err) + "\n```\n\n")
		}
		if r.Doc.Prose != "" {
			b.WriteString(r.Doc.Prose + "\n\n")
		}
		for _, png := range r.Captures {
			b.WriteString("![" + png + "](" + png + ")\n\n")
		}
		if len(r.Sidecars) > 0 {
			links := make([]string, 0, len(r.Sidecars))
			for _, sc := range r.Sidecars {
				links = append(links, "["+sc+"]("+sc+")")
			}
			b.WriteString("Sidecars: " + strings.Join(links, " · ") + "\n\n")
		}
		if len(r.Doc.Spec.Env) > 0 {
			keys := make([]string, 0, len(r.Doc.Spec.Env))
			for k := range r.Doc.Spec.Env {
				keys = append(keys, k+"="+r.Doc.Spec.Env[k])
			}
			sort.Strings(keys)
			b.WriteString("Launch: `" + r.Doc.Spec.Launch + "` · " + strings.Join(keys, " ") + "\n\n")
		}
		if r.Doc.SQL != "" {
			b.WriteString("```sql\n" + r.Doc.SQL + "\n```\n\n")
		}
		if r.Doc.Trace != "" {
			b.WriteString("```json\n" + r.Doc.Trace + "\n```\n")
		}
	}
	if err = os.WriteFile(filepath.Join(outDir, "index.md"), []byte(b.String()), 0o644); err != nil {
		return eh.Errorf("unable to write the gallery index: %w", err)
	}
	return nil
}

// PlainError renders an error with its fields and without colour — what a
// step read and what it expected are fields, and a bare message drops them.
func PlainError(err error) string {
	var b strings.Builder
	eh.FormatErrorPlain(&b, err)
	// The chain and its fields say what failed; the stack says where in the
	// runner, which is not what a scene author is asking.
	text, _, _ := strings.Cut(b.String(), "\nStack trace")
	return strings.TrimSpace(text)
}
