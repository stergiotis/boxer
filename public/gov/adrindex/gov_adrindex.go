// Package adrindex generates doc/adr/INDEX.md, a table of every ADR with its
// number, title, status, date and the ADRs that supersede it.
//
// The rows come from the ADRs' front matter and first heading, read by
// [github.com/stergiotis/boxer/public/gov/adrcorpus.ParseDir]. The output is
// a pure function of the ADR files — no timestamps — so TestIndexIsCurrent
// can require byte equality against the committed file. The richer overview
// (code evidence, sub-items) is `boxer adr`, which needs a built binary and
// clickhouse local; this index needs neither to read.
package adrindex

//go:generate sh -c "go run -tags=\"$(cat ../../../tags)\" github.com/stergiotis/boxer/public/app gov adrindex --dir ../../../doc/adr"

import (
	"bytes"
	"fmt"
	"os"
	"path"
	"strings"

	"github.com/stergiotis/boxer/public/gov/adrcorpus"
	"github.com/stergiotis/boxer/public/observability/eh/eb"
)

// Render returns the full INDEX.md content for adrs, in the order given.
func Render(adrs []adrcorpus.Adr) []byte {
	var b bytes.Buffer
	b.WriteString(`---
type: reference
audience: contributor
status: draft
generated: true
generator: boxer gov adrindex
---

> **Status: draft — pre-human-review.** Machine-extracted index over the
> ADRs beside it; regenerate with ` + "`boxer gov adrindex`" + ` after adding
> an ADR or changing a status. Review happens on the ADRs, not here.

# ADR index

<!-- Generated by ` + "`boxer gov adrindex`" + `. Do not edit by hand. -->

Every architecture decision record, by number, with the status and date its
front matter states. An ADR's lifecycle — proposed, accepted, superseded,
withdrawn, deferred — is described in the
[documentation standard](../DOCUMENTATION_STANDARD.md).

| ADR | Title | Status | Date | Superseded by |
| --- | --- | --- | --- | --- |
`)
	for i := range adrs {
		a := &adrs[i]
		fmt.Fprintf(&b, "| [%04d](./%s) | %s | %s | %s | %s |\n",
			a.Num, path.Base(a.Path), cell(a.Title), cell(a.Status), cell(a.Date), cell(a.SupersededBy))
	}
	return b.Bytes()
}

// cell makes s safe inside one Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

// Generate writes the index for the ADRs in dir to outPath.
func Generate(dir string, outPath string) (err error) {
	var adrs []adrcorpus.Adr
	adrs, err = adrcorpus.ParseDir(dir)
	if err != nil {
		return
	}
	err = os.WriteFile(outPath, Render(adrs), 0o644)
	if err != nil {
		err = eb.Build().Str("out", outPath).Errorf("writing adr index: %w", err)
	}
	return
}

// Check reports an error when outPath does not hold exactly what Generate
// would write for dir — the index has drifted from the ADRs.
func Check(dir string, outPath string) (err error) {
	var adrs []adrcorpus.Adr
	adrs, err = adrcorpus.ParseDir(dir)
	if err != nil {
		return
	}
	var have []byte
	have, err = os.ReadFile(outPath)
	if err != nil {
		err = eb.Build().Str("out", outPath).Errorf("reading adr index: %w", err)
		return
	}
	if !bytes.Equal(have, Render(adrs)) {
		err = eb.Build().Str("out", outPath).Errorf("adr index drifted from the ADRs; regenerate with `boxer gov adrindex`")
	}
	return
}
