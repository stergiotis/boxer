package releasenotes

import (
	"bytes"
	"fmt"
	"path"
	"strings"
)

// shortHash is the abbreviation the notes print; fixed rather than git's
// adaptive one so the output does not depend on the repository's size.
func shortHash(h string) (s string) {
	if len(h) > 12 {
		return h[:12]
	}
	return h
}

// Render emits the notes as markdown. outDir is the module-relative directory
// the document will live in, used to make links to migration notes relative.
// apidiff, when non-empty, is the output of scripts/ci/apidiff.sh for the same
// range and is included verbatim.
func Render(n Notes, outDir string, apidiff string) (src []byte) {
	var b bytes.Buffer
	cmdLine := fmt.Sprintf("boxer gov releasenotes --from %s --to %s", n.From, n.To)
	fmt.Fprintf(&b, `---
type: reference
audience: consumers pinning a version of this module
status: draft
generated: true
generator: boxer gov releasenotes
---

> **Status: draft — pre-human-review.** Generated by `+"`%s`"+`;
> regenerated when a version is tagged. Do not edit by hand. Breaking changes
> are the commits whose subject carries `+"`!`"+`; see VERSIONING.md.

# Release notes: %s..%s

%d commit(s) in the range.
`, cmdLine, n.From, n.To, n.NumCommits)

	b.WriteString("\n## Build requirements\n\n")
	writeFloor(&b, "`go` directive", n.GoFrom, n.GoTo)
	writeFloor(&b, "`toolchain` line", n.ToolFrom, n.ToolTo)

	fmt.Fprintf(&b, "\n## Breaking changes (%d)\n", len(n.Breaking))
	if len(n.Breaking) == 0 {
		b.WriteString("\nNo commit in the range is marked breaking.\n")
	}
	for _, c := range n.Breaking {
		fmt.Fprintf(&b, "\n### %s\n\n`%s`", c.Subject, shortHash(c.Hash))
		if c.Breaks != "" {
			fmt.Fprintf(&b, " — %s\n", c.Breaks)
		} else {
			b.WriteString(" — the commit has no `Breaks:` paragraph; read its body.\n")
		}
	}

	fmt.Fprintf(&b, "\n## Packages removed or renamed (%d)\n\n", len(n.Packages))
	if len(n.Packages) == 0 {
		b.WriteString("None.\n")
	}
	for _, p := range n.Packages {
		if p.Kind == PackageChangeKindRenamed {
			fmt.Fprintf(&b, "- `%s` → `%s`\n", p.Dir, p.To)
		} else {
			fmt.Fprintf(&b, "- `%s` (removed)\n", p.Dir)
		}
	}

	direct, indirect := 0, 0
	for _, m := range n.Modules {
		if m.Indirect {
			indirect++
		} else {
			direct++
		}
	}
	fmt.Fprintf(&b, "\n## Dependency floors\n\n%d direct and %d indirect requirement(s) changed.", direct, indirect)
	if direct > 0 {
		b.WriteString(" Direct requirements:\n\n| Module | From | To |\n| --- | --- | --- |\n")
		for _, m := range n.Modules {
			if !m.Indirect {
				fmt.Fprintf(&b, "| `%s` | %s | %s |\n", m.Path, orDash(m.From), orDash(m.To))
			}
		}
	} else {
		b.WriteString("\n")
	}

	b.WriteString("\n## Contract snapshots\n\n")
	if len(n.Contracts) == 0 {
		b.WriteString("No snapshot under `contracts/` changed.\n")
	}
	for _, c := range n.Contracts {
		status, file, _ := strings.Cut(c, "\t")
		fmt.Fprintf(&b, "- `%s` (%s)\n", strings.ReplaceAll(file, "\t", " → "), status)
	}

	b.WriteString("\n## Migration notes added\n\n")
	if len(n.Migrations) == 0 {
		b.WriteString("None.\n")
	}
	for _, m := range n.Migrations {
		fmt.Fprintf(&b, "- [%s](%s)\n", path.Base(m), relLink(outDir, m))
	}

	if apidiff != "" {
		b.WriteString("\n## API differences in Stable packages\n\nOutput of `scripts/ci/apidiff.sh` for the same range.\n\n```text\n")
		b.WriteString(strings.TrimRight(apidiff, "\n"))
		b.WriteString("\n```\n")
	}
	return b.Bytes()
}

func writeFloor(b *bytes.Buffer, what string, from string, to string) {
	switch {
	case from == to && from == "":
		fmt.Fprintf(b, "- %s: absent at both ends.\n", what)
	case from == to:
		fmt.Fprintf(b, "- %s: unchanged at %s.\n", what, from)
	default:
		fmt.Fprintf(b, "- %s: %s → %s.\n", what, orDash(from), orDash(to))
	}
}

func orDash(s string) (r string) {
	if s == "" {
		return "—"
	}
	return s
}

// relLink makes target (module-relative) relative to the directory dir
// (module-relative).
func relLink(dir string, target string) (rel string) {
	dir = path.Clean(dir)
	if dir == "." || dir == "" {
		return target
	}
	ups := strings.Count(dir, "/") + 1
	return strings.Repeat("../", ups) + target
}
