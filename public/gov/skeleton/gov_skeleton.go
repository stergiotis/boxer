// Package skeleton emits and reconciles the repository mechanics a boxer
// consumer would otherwise copy by hand (ADR-0179).
//
// Standards text, templates, lint rules and library conventions all reach a
// consumer through the go.mod pin. The mechanics did not: a launcher, a path
// helper, a doc seeder, a lint wrapper. Those were copied once and then drifted
// — two consumer repositories were found carrying build-tag families boxer had
// retired months earlier, and a lint script that had diverged into an
// independent 317-line reimplementation.
//
// The fix is to generate them. Emitted files carry a DO NOT EDIT header and are
// reconciled by [Check]: a copy that differs from what this boxer would emit is
// drift, and fails. The marker deliberately carries no version or timestamp, so
// a boxer bump that does not change a template does not rewrite the file and
// leave every consumer permanently red.
//
// One seam is conceded, in one known place (ADR-0179 §QOC O1): the emitted lint
// wrapper sources an optional scripts/ci/lint-local.sh, never generated and
// never checked, for steps genuinely local to a repository — a Rust crate, a
// capture pipeline, a hardware gate. Without it a consumer with local needs
// abandons the tool on day one; with an open-ended suppression list instead,
// exemptions become drift with permission.
//
// Files the consumer owns — AGENTS.md, tags, the entry point — are never
// overwritten. They carry repository-specific content, so they are seeded when
// absent and reported but left alone when present.
package skeleton

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/stergiotis/boxer/public/gov/buildtags"
	"github.com/stergiotis/boxer/public/observability/eh/eb"
)

// GeneratedMarker is the sentinel an emitted file carries. It follows the Go
// convention's wording so the same greps and lint filters find it.
const GeneratedMarker = "Code generated by boxer gov skeleton. DO NOT EDIT."

// OwnershipE says who owns a skeleton file's content.
type OwnershipE uint8

const (
	// OwnershipGenerated — boxer owns it. Overwritten by Write, reconciled
	// by Check.
	OwnershipGenerated OwnershipE = 1
	// OwnershipSeeded — the consumer owns it. Written only when absent;
	// never overwritten, never reconciled.
	OwnershipSeeded OwnershipE = 2
)

var AllOwnerships = []OwnershipE{OwnershipGenerated, OwnershipSeeded}

func (inst OwnershipE) String() (s string) {
	switch inst {
	case OwnershipGenerated:
		s = "generated"
	case OwnershipSeeded:
		s = "seeded"
	default:
		s = "unknown"
	}
	return
}

// Params is what a template needs to know about the repository.
//
// Everything here is derivable from go.mod; [DeriveParamsE] does that, and the
// CLI lets each field be overridden.
type Params struct {
	// Module is the Go module path, e.g. github.com/owner/thing.
	Module string
	// Name is the repository's short name, used for the launcher script and
	// in prose. Defaults to the last element of Module.
	Name string
	// AppPackage is the import-relative path of the single entry point.
	AppPackage string
	// RequiredTags is the comma-separated build-tag set boxer requires of a
	// consumer. Read from the build-tag contract rather than restated, so
	// the seeded manifest and the check that polices it cannot disagree.
	RequiredTags string
}

func (inst Params) validateE() (err error) {
	if inst.Module == "" {
		err = eb.Build().Errorf("module path is empty")
		return
	}
	if inst.Name == "" {
		err = eb.Build().Str("module", inst.Module).Errorf("repository name is empty")
		return
	}
	if strings.ContainsAny(inst.Name, "/\\") {
		err = eb.Build().Str("name", inst.Name).Errorf("repository name must not contain a path separator")
		return
	}
	return
}

// DeriveParamsE reads go.mod under dir and fills in the defaults.
func DeriveParamsE(dir string) (p Params, err error) {
	if dir == "" {
		dir = "."
	}
	path := filepath.Join(dir, "go.mod")
	var raw []byte
	raw, err = os.ReadFile(path)
	if err != nil {
		err = eb.Build().Str("path", path).Errorf("read go.mod: %w", err)
		return
	}
	for line := range strings.SplitSeq(string(raw), "\n") {
		line = strings.TrimSpace(line)
		rest, found := strings.CutPrefix(line, "module ")
		if !found {
			continue
		}
		p.Module = strings.TrimSpace(rest)
		break
	}
	if p.Module == "" {
		err = eb.Build().Str("path", path).Errorf("go.mod declares no module path")
		return
	}
	p.Name = p.Module[strings.LastIndex(p.Module, "/")+1:]
	p.AppPackage = "./public/app"
	p.RequiredTags = strings.Join(buildtags.RequiredTags, ",")
	return
}

// File is one member of the skeleton.
type File struct {
	// Path is relative to the repository root. A leading "{{.Name}}" is
	// expanded, so the launcher lands as <repo>.sh.
	Path      string
	Ownership OwnershipE
	Mode      os.FileMode
	Template  string
	// SeedGuardDir, when set, suppresses seeding if that directory already
	// holds any .md file.
	//
	// It exists for the adoption ADR, whose path hardcodes a number. In an
	// empty repository doc/adr/0001-… is free; in one that already has a
	// corpus it collides with whatever ADR-0001 already is, and a repository
	// with an ADR corpus has either already recorded its adoption or will
	// number that record itself. Seeding is for a repository that has not
	// started, not for one that has.
	SeedGuardDir string
}

// seedSuppressed reports whether f's guard directory already has content.
func seedSuppressed(dir string, f File) (skip bool) {
	if f.SeedGuardDir == "" {
		return false
	}
	entries, err := os.ReadDir(filepath.Join(dir, f.SeedGuardDir))
	if err != nil {
		return false
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".md") {
			return true
		}
	}
	return false
}

// StatusE is what Check found for one file.
type StatusE uint8

const (
	// StatusOk — content matches what boxer would emit.
	StatusOk StatusE = 1
	// StatusDrift — a generated file differs from what boxer would emit.
	StatusDrift StatusE = 2
	// StatusAbsent — the file is missing.
	StatusAbsent StatusE = 3
	// StatusOwned — a seeded file exists; its content is the consumer's
	// business and is not compared.
	StatusOwned StatusE = 4
)

var AllStatuses = []StatusE{StatusOk, StatusDrift, StatusAbsent, StatusOwned}

func (inst StatusE) String() (s string) {
	switch inst {
	case StatusOk:
		s = "ok"
	case StatusDrift:
		s = "drift"
	case StatusAbsent:
		s = "absent"
	case StatusOwned:
		s = "owned"
	default:
		s = "unknown"
	}
	return
}

// Result is Check's verdict for one file.
type Result struct {
	Path      string
	Ownership OwnershipE
	Status    StatusE
	// FirstDiffLine is the 1-based line where a drifting file first differs,
	// 0 when it does not apply. Want and Got are that line's content.
	FirstDiffLine int32
	Want          string
	Got           string
}

// Blocking reports whether this result should fail a reconciliation.
//
// Only generated files block: drift in one, or its absence. A seeded file that
// is missing is a to-do for a new repository, not a failure — the consumer may
// legitimately not have written its entry point yet.
func (inst Result) Blocking() (bad bool) {
	if inst.Ownership != OwnershipGenerated {
		return false
	}
	return inst.Status == StatusDrift || inst.Status == StatusAbsent
}

// RenderE expands one file's template and its path against p.
func RenderE(f File, p Params) (path string, content []byte, err error) {
	err = p.validateE()
	if err != nil {
		return
	}

	path, err = expandE("path:"+f.Path, f.Path, p)
	if err != nil {
		return
	}

	var s string
	s, err = expandE("body:"+f.Path, f.Template, p)
	if err != nil {
		return
	}
	content = []byte(s)
	return
}

func expandE(name string, text string, p Params) (out string, err error) {
	// Missingkey=error turns a template referring to a field that does not
	// exist into a loud failure rather than a file containing "<no value>".
	t, parseErr := template.New(name).Option("missingkey=error").Parse(text)
	if parseErr != nil {
		err = eb.Build().Str("template", name).Errorf("parse template: %w", parseErr)
		return
	}
	var b bytes.Buffer
	b.Grow(len(text) + 64)
	execErr := t.Execute(&b, p)
	if execErr != nil {
		err = eb.Build().Str("template", name).Errorf("execute template: %w", execErr)
		return
	}
	out = b.String()
	return
}

// firstDiff returns the 1-based line number at which want and got first differ,
// with both lines, or 0 when they are identical.
func firstDiff(want []byte, got []byte) (line int32, wantLine string, gotLine string) {
	w := strings.Split(string(want), "\n")
	g := strings.Split(string(got), "\n")
	n := min(len(w), len(g))
	for i := range n {
		if w[i] != g[i] {
			return int32(i + 1), w[i], g[i]
		}
	}
	if len(w) == len(g) {
		return 0, "", ""
	}
	// One is a prefix of the other; the first extra line is the difference.
	if len(w) > len(g) {
		return int32(n + 1), w[n], "(end of file)"
	}
	return int32(n + 1), "(end of file)", g[n]
}

// CheckE reconciles the on-disk skeleton under dir against what boxer would
// emit, returning one Result per file in files order.
func CheckE(dir string, files []File, p Params) (results []Result, err error) {
	if dir == "" {
		dir = "."
	}
	results = make([]Result, 0, len(files))
	for _, f := range files {
		var rel string
		var want []byte
		rel, want, err = RenderE(f, p)
		if err != nil {
			return
		}

		r := Result{Path: rel, Ownership: f.Ownership}
		got, readErr := os.ReadFile(filepath.Join(dir, rel))
		switch {
		case readErr != nil && os.IsNotExist(readErr) && seedSuppressed(dir, f):
			// Suppressed seeds are neither present nor owed.
			continue
		case readErr != nil && os.IsNotExist(readErr):
			r.Status = StatusAbsent
		case readErr != nil:
			err = eb.Build().Str("path", rel).Errorf("read: %w", readErr)
			return
		case f.Ownership == OwnershipSeeded:
			// Present and the consumer's business. Never compared.
			r.Status = StatusOwned
		case bytes.Equal(want, got):
			r.Status = StatusOk
		default:
			r.Status = StatusDrift
			r.FirstDiffLine, r.Want, r.Got = firstDiff(want, got)
		}
		results = append(results, r)
	}
	return
}

// WriteE materialises the skeleton under dir.
//
// Generated files are written unconditionally. Seeded files are written only
// when absent, so a consumer's own entry point, tag manifest and AGENTS.md are
// never clobbered by a reconciliation. Returns the paths actually written.
func WriteE(dir string, files []File, p Params) (written []string, err error) {
	if dir == "" {
		dir = "."
	}
	written = make([]string, 0, len(files))
	for _, f := range files {
		var rel string
		var content []byte
		rel, content, err = RenderE(f, p)
		if err != nil {
			return
		}
		full := filepath.Join(dir, rel)

		if f.Ownership == OwnershipSeeded {
			if _, statErr := os.Stat(full); statErr == nil {
				continue
			}
			if seedSuppressed(dir, f) {
				continue
			}
		}

		// Never write through a symlink. Following one clobbers a file at a
		// path this package does not believe it owns — a real repository had
		// <name>.sh symlinked to its actual launcher, and a naive write
		// replaced that launcher instead. The target could equally point
		// outside the repository.
		if fi, lstatErr := os.Lstat(full); lstatErr == nil && fi.Mode()&os.ModeSymlink != 0 {
			dest, _ := os.Readlink(full)
			err = eb.Build().
				Str("path", rel).
				Str("target", dest).
				Errorf("refusing to write through a symlink; remove it, or point --name at the real file")
			return
		}

		err = os.MkdirAll(filepath.Dir(full), 0o755)
		if err != nil {
			err = eb.Build().Str("path", full).Errorf("mkdir: %w", err)
			return
		}
		mode := f.Mode
		if mode == 0 {
			mode = 0o644
		}
		err = os.WriteFile(full, content, mode)
		if err != nil {
			err = eb.Build().Str("path", full).Errorf("write: %w", err)
			return
		}
		// WriteFile does not chmod an existing file.
		err = os.Chmod(full, mode)
		if err != nil {
			err = eb.Build().Str("path", full).Errorf("chmod: %w", err)
			return
		}
		written = append(written, rel)
	}
	return
}
