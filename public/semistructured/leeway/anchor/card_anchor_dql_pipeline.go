package anchor

import (
	"github.com/stergiotis/boxer/public/db/clickhouse/dsl/nanopass"
	"github.com/stergiotis/boxer/public/db/clickhouse/dsl/nanopass/passes"
	"github.com/stergiotis/boxer/public/semistructured/leeway/lwsql"
)

// This file wires the anchor demo queries to the nanopass SQL pipeline. The
// `card_anchor_dql_query*.sql` files are authored in *friendly* form — leeway
// column handles (`symbol:value`, `geoPoint:*`, ADR-0116) and unqualified
// table names — and the pipeline below rewrites them into the physical,
// canonical, grammar2-valid SQL that actually executes (the
// `card_anchor_dql_query*.out.sql` artifacts, regenerated by
// TestDqlPipelineGeneration). The stage split mirrors a host's pre-execute
// seam (ADR-0108): editors keep the friendly text, executors ship the
// rewritten body.

// DqlPhysicalColumnNames returns the anchor table's physical column names,
// read off the generated Arrow schema (card_anchor_dml.out.go) rather than
// re-derived from the TableDesc: the queries resolve against exactly the
// columns the DML artifact ships.
func DqlPhysicalColumnNames() (names []string) {
	fields := CreateSchemaTestTable().Fields()
	names = make([]string, 0, len(fields))
	for _, f := range fields {
		names = append(names, f.Name)
	}
	return
}

// NewDqlSchemaProvider serves the anchor.facts column list to schema-aware
// passes without a live server.
func NewDqlSchemaProvider() *passes.StaticSchemaProvider {
	return passes.NewStaticSchemaProvider(map[string][]string{
		"anchor.facts": DqlPhysicalColumnNames(),
	})
}

// NewDqlResolver builds the lwsql resolver that maps friendly column handles
// (`section:column`, `section:*`) onto anchor's physical column names.
func NewDqlResolver() *lwsql.Resolver {
	return lwsql.NewResolver(NewDqlSchemaProvider())
}

// DqlPreExecuteStages returns the pre-execute rewrite chain, one Pass per
// stage so callers can observe intermediate forms. Order follows the host
// convention (see play.RegisterPasses): canonicalize first so later passes
// consume canonical shapes; ValidateGrammar2 is the terminal proof that the
// output is canonical-only SQL. diag receives one ColumnDiagnostic per
// unresolvable handle (nil to drop them silently, as on an execution path).
func DqlPreExecuteStages(resolver *lwsql.Resolver, diag func(passes.ColumnDiagnostic)) []nanopass.Pass {
	return []nanopass.Pass{
		passes.StripComments,
		passes.CanonicalizeFull(100),
		passes.QualifyTables(`"anchor"`),
		passes.ResolveColumnNames(resolver, "anchor", diag),
		nanopass.ValidateGrammar2,
	}
}

// NewDqlPreExecutePipeline composes DqlPreExecuteStages into a single Pass.
func NewDqlPreExecutePipeline(resolver *lwsql.Resolver, diag func(passes.ColumnDiagnostic)) nanopass.Pass {
	return nanopass.Sequence("AnchorDqlPreExecute", DqlPreExecuteStages(resolver, diag)...)
}
