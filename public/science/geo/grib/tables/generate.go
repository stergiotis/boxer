// Generated is the set of files [GenerateE] produces for wmo/: one
// tab-separated file per kind and the version stamp.
type Generated struct {
	Version   string
	Codes     []byte
	Flags     []byte
	Templates []byte
	Centres   []byte
}

var (
	codeFile     = regexp.MustCompile(`^GRIB2_CodeFlag_(\d+)_(\d+)(?:_(\d+)_(\d+))?_CodeTable_en\.csv$`)
	flagFile     = regexp.MustCompile(`^GRIB2_CodeFlag_(\d+)_(\d+)_FlagTable_en\.csv$`)
	templateFile = regexp.MustCompile(`^GRIB2_Template_(\d+)_(\d+)_\w+_en\.csv$`)
)

// GenerateE reads a checkout of wmo-im/GRIB2 (grib2Dir, at the tag named
// by version) and of wmo-im/CCT (cctDir) and reduces them to the embedded
// form: every code table row as table, low, high, meaning, unit, status;
// every flag table row as table, bit, value, meaning, status; every template
// row as template, octets, count, contents, code table, flag table, status;
// and common table C-11 as code, name, status. Notes are dropped; the
// meanings are the WMO's words.
func GenerateE(grib2Dir, cctDir, version string) (g Generated, err error) {
	entries, err := os.ReadDir(grib2Dir)
	if err != nil {
		err = eb.Build().Str("dir", grib2Dir).Errorf("read grib2 tables: %w", err)
		return
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	var codes, flags, templates bytes.Buffer
	stamp := "# generated by tables.GenerateE from wmo-im/GRIB2 " + version + "; do not edit\n"
	codes.WriteString(stamp)
	flags.WriteString(stamp)
	templates.WriteString(stamp)
	for _, name := range names {
		path := filepath.Join(grib2Dir, name)
		switch {
		case codeFile.MatchString(name):
			m := codeFile.FindStringSubmatch(name)
			table := m[1] + "." + m[2]
			if m[3] != "" {
				table += "." + m[3] + "." + m[4]
			}
			err = appendCodeTableE(&codes, path, table)
		case flagFile.MatchString(name):
			m := flagFile.FindStringSubmatch(name)
			err = appendFlagTableE(&flags, path, m[1]+"."+m[2])
		case templateFile.MatchString(name):
			m := templateFile.FindStringSubmatch(name)
			err = appendTemplateE(&templates, path, m[1]+"."+m[2])
		}
		if err != nil {
			return
		}
	}
	var centres bytes.Buffer
	centres.WriteString("# generated by tables.GenerateE from wmo-im/CCT C11.csv; do not edit\n")
	err = appendCentresE(&centres, filepath.Join(cctDir, "C11.csv"))
	if err != nil {
		return
	}
	g = Generated{Version: version, Codes: codes.Bytes(), Flags: flags.Bytes(), Templates: templates.Bytes(), Centres: centres.Bytes()}
	return
}

// WriteE writes the generated files into dir.
func (inst Generated) WriteE(dir string) (err error) {
	for name, b := range map[string][]byte{"codes.tsv": inst.Codes, "flags.tsv": inst.Flags, "templates.tsv": inst.Templates, "centres.tsv": inst.Centres, "VERSION": []byte(inst.Version + "\n")} {
		err = os.WriteFile(filepath.Join(dir, name), b, 0o644)
		if err != nil {
			err = eb.Build().Str("file", name).Errorf("write: %w", err)
			return
		}
	}
	return
}

func readCSVE(path string) (header map[string]int, records [][]string, err error) {
	f, err := os.Open(path)
	if err != nil {
		return
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.FieldsPerRecord = -1
	r.LazyQuotes = true
	all, err := r.ReadAll()
	if err != nil {
		err = eb.Build().Str("file", path).Errorf("csv: %w", err)
		return
	}
	if len(all) == 0 {
		err = eb.Build().Str("file", path).Errorf("empty csv")
		return
	}
	header = map[string]int{}
	for i, h := range all[0] {
		header[strings.TrimPrefix(h, "\uFEFF")] = i
	}
	records = all[1:]
	return
}

func field(rec []string, header map[string]int, name string) (v string) {
	i, ok := header[name]
	if ok && i < len(rec) {
		v = clean(rec[i])
	}
	return
}

// clean makes a value safe for a tab-separated line.
func clean(s string) (out string) {
	out = strings.Join(strings.Fields(strings.ReplaceAll(strings.ReplaceAll(s, "\t", " "), "\n", " ")), " ")
	return
}

// parseRange reads "12" or "12-25".
func parseRange(s string) (lo, hi uint32, ok bool) {
	s = strings.TrimSpace(s)
	if s == "" {
		return
	}
	a, b, isRange := strings.Cut(s, "-")
	l, err := strconv.ParseUint(strings.TrimSpace(a), 10, 32)
	if err != nil {
		return
	}
	lo, hi = uint32(l), uint32(l)
	if isRange {
		h, err := strconv.ParseUint(strings.TrimSpace(b), 10, 32)
		if err != nil {
			return
		}
		hi = uint32(h)
	}
	ok = true
	return
}

func appendCodeTableE(w io.Writer, path, table string) (err error) {
	header, records, err := readCSVE(path)
	if err != nil {
		return
	}
	for _, rec := range records {
		lo, hi, ok := parseRange(field(rec, header, "CodeFlag"))
		if !ok {
			continue
		}
		fmt.Fprintf(w, "%s\t%d\t%d\t%s\t%s\t%s\n", table, lo, hi, field(rec, header, "MeaningParameterDescription_en"), field(rec, header, "UnitComments_en"), field(rec, header, "Status"))
	}
	return
}

func appendFlagTableE(w io.Writer, path, table string) (err error) {
	header, records, err := readCSVE(path)
	if err != nil {
		return
	}
	for _, rec := range records {
		bit, _, ok := parseRange(field(rec, header, "CodeFlag"))
		if !ok {
			continue
		}
		val, err2 := strconv.ParseUint(field(rec, header, "Value"), 10, 8)
		if err2 != nil {
			continue
		}
		fmt.Fprintf(w, "%s\t%d\t%d\t%s\t%s\n", table, bit, val, field(rec, header, "MeaningParameterDescription_en"), field(rec, header, "Status"))
	}
	return
}

func appendTemplateE(w io.Writer, path, template string) (err error) {
	header, records, err := readCSVE(path)
	if err != nil {
		return
	}
	for _, rec := range records {
		octets := field(rec, header, "OctetNo")
		if octets == "" {
			continue
		}
		count, _ := strconv.Atoi(field(rec, header, "OctetCount"))
		fmt.Fprintf(w, "%s\t%s\t%d\t%s\t%s\t%s\t%s\n", template, octets, count, field(rec, header, "Contents_en"), field(rec, header, "codeTable"), field(rec, header, "flagTable"), field(rec, header, "Status"))
	}
	return
}

func appendCentresE(w io.Writer, path string) (err error) {
	header, records, err := readCSVE(path)
	if err != nil {
		return
	}
	for _, rec := range records {
		code := field(rec, header, "GRIB2_BUFR4")
		if code == "" {
			continue
		}
		n, err2 := strconv.ParseUint(code, 10, 32)
		if err2 != nil {
			continue
		}
		fmt.Fprintf(w, "%d\t%s\t%s\n", n, field(rec, header, "OriginatingGeneratingCentre_en"), field(rec, header, "Status"))
	}
	return
}
