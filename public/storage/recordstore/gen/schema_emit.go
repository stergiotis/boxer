package gen

import (
	"fmt"
	"go/format"
	"strings"

	"github.com/stergiotis/boxer/public/observability/eh/eb"
	"github.com/stergiotis/boxer/public/storage/recordstore"
)

// emitSchema renders <store>_schema.out.go: the generated column list,
// parsed from the CREATE TABLE this run composed, and the stamp that
// statement carries (ADR-0387). It is a file of its own because the store
// glue is emitted before the DDL is composed.
func (inst Input) emitSchema(cols []recordstore.ColumnSpec, stamp string) (code []byte, err error) {
	var sb strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&sb, format+"\n", args...) }
	p("// Code generated by github.com/stergiotis/boxer/public/storage/recordstore/gen — DO NOT EDIT.")
	p("")
	p("package %s", inst.PackageName)
	p("")
	p("import %q", "github.com/stergiotis/boxer/public/storage/recordstore")
	p("")
	p("// %sColumns is the column list of %s_ddl_clickhouse.out.sql, in its", inst.StoreName, inst.TableName)
	p("// order: what a schema check compares a live table with, and what")
	p("// `boxer schema plan` derives ADD COLUMN statements from.")
	p("var %sColumns = []recordstore.ColumnSpec{", inst.StoreName)
	for _, c := range cols {
		p("\t{Name: %q, Type: %q, Codec: %q},", c.Name, c.Type, c.Codec)
	}
	p("}")
	p("")
	p("// %sTableStamp is the COMMENT the store's CREATE TABLE writes: the", inst.StoreName)
	p("// schema that created a table, as a schema check reads it back.")
	p("const %sTableStamp = %q", inst.StoreName, stamp)
	raw := []byte(sb.String())
	code, err = format.Source(raw)
	if err != nil {
		err = eb.Build().Str("emitted", string(raw)).Errorf("gofmt rejected schema output: %w", err)
	}
	return
}
