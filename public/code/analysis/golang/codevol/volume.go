package codevol

import (
	"go/scanner"
	"go/token"
	"os"
	"regexp"
	"slices"
	"strings"
)

// Volume is a line tally over a set of source files.
type Volume struct {
	Files int
	// CodeLines counts lines bearing at least one non-comment token,
	// CommentLines lines bearing only comment tokens, BlankLines the rest.
	// A line with both code and a trailing comment counts as code only, so
	// the three always sum to the file's line count.
	CodeLines    int
	CommentLines int
	BlankLines   int
	// GeneratedFiles counts files carrying the conventional marker. It
	// matters more than it looks: 40% of this repository's own compiled
	// lines are generated, and a first-party total that hides that overstates
	// what anyone wrote.
	GeneratedFiles int
	GeneratedCode  int
	// OtherLangLines counts the C, C++, assembly and header files compiled
	// with a cgo package — invisible to any Go-only count, and 377k lines in
	// this module's dependency closure.
	OtherLangLines int
	// Generators names the tools that wrote the generated files, sorted and
	// deduplicated (ADR-0173 §SD10). A slice rather than one string because a
	// quarter of this repository's generated packages carry more than one
	// tool, and the leeway packages carry three.
	Generators []string
}

func (v *Volume) add(o Volume) {
	v.Files += o.Files
	v.CodeLines += o.CodeLines
	v.CommentLines += o.CommentLines
	v.BlankLines += o.BlankLines
	v.GeneratedFiles += o.GeneratedFiles
	v.GeneratedCode += o.GeneratedCode
	v.OtherLangLines += o.OtherLangLines
	v.Generators = mergeGenerators(v.Generators, o.Generators)
}

// mergeGenerators unions src into dst, keeping it sorted and deduplicated so
// a package's list is stable across runs whatever order its files arrive in.
func mergeGenerators(dst []string, src []string) []string {
	for _, s := range src {
		i, found := slices.BinarySearch(dst, s)
		if found {
			continue
		}
		dst = slices.Insert(dst, i, s)
	}
	return dst
}

// generatedRe is the convention from https://go.dev/s/generatedcode: the line
// must match exactly, on its own, before the package clause. The capture is
// the free-form middle the convention leaves entirely to the tool.
var generatedRe = regexp.MustCompile(`^// Code generated (.*) DO NOT EDIT\.$`)

// antlrRe matches ANTLR's variant, which names its input before the tool:
// "Code generated from Foo.g4 by ANTLR 4.13.2." Only the tool is kept — see
// ADR-0173 §SD10 on why a file-to-input relation is deliberately not modelled.
// Non-greedy, so an input path containing " by " does not swallow the tool.
var antlrRe = regexp.MustCompile(`^from .+? by (.+)$`)

// invokerRe strips a trailing parenthetical. Several generators append the
// package that invoked them, which varies per call site: keeping it splits
// one tool into a bucket per caller, and dropping it takes this repository's
// vocabulary from 36 strings to 17.
var invokerRe = regexp.MustCompile(`\s*\([^)]*\)\s*$`)

// GeneratorUnknown is reported for a file whose marker is present but carries
// no usable tool name.
const GeneratorUnknown = "unknown"

// GeneratorOf extracts the tool from a generated-code marker line, reporting
// ok only when the line is such a marker.
//
// The tool field is free-form prose that nothing validates — values in this
// repository run from an import path through a shell invocation to
// "copy paste" (and, in four files, "copy pase") — so this trims and
// normalises rather than parsing, and never rejects a marker it matched:
// there is always some string to group by.
func GeneratorOf(line string) (tool string, ok bool) {
	m := generatedRe.FindStringSubmatch(strings.TrimRight(line, "\r"))
	if m == nil {
		return
	}
	ok = true
	tool = strings.TrimSpace(m[1])
	if a := antlrRe.FindStringSubmatch(tool); a != nil {
		tool = a[1]
	}
	// Both spellings occur: "generated by X" is the convention, "generated
	// by: X" is used by a handful of stdlib generators.
	if rest, cut := strings.CutPrefix(tool, "by:"); cut {
		tool = strings.TrimSpace(rest)
	} else {
		tool = strings.TrimPrefix(tool, "by ")
	}
	// TrimRight, not Trim: a leading "." is load-bearing in the several
	// markers that name a script by relative path.
	tool = strings.TrimRight(tool, " \t.;,—-")
	tool = invokerRe.ReplaceAllString(tool, "")
	tool = strings.TrimRight(tool, " \t.;,—-")
	if tool == "" {
		tool = GeneratorUnknown
	}
	return
}

// CountFiles tallies goPaths (classified with go/scanner) and otherPaths
// (counted as raw lines).
//
// Callers pass file paths rather than a loader's package type on purpose:
// this keeps the package free of golang.org/x/tools, so it can be linked into
// builds that must not carry a Go toolchain's worth of analysis code.
//
// Unreadable files are skipped rather than failed on — a volume tally is
// best-effort evidence, and one unreadable file should not empty a table.
func CountFiles(goPaths []string, otherPaths []string) (v Volume) {
	for _, p := range goPaths {
		c, ok := countGoFile(p)
		if !ok {
			continue
		}
		v.add(c)
	}
	for _, p := range otherPaths {
		n, ok := countRawLines(p)
		if !ok {
			continue
		}
		v.OtherLangLines += n
	}
	return
}

// countGoFile classifies one Go file's lines.
//
// go/scanner rather than a line-oriented regex, because "//" inside a string
// literal is common in this repository (URLs, import paths, SQL) and a
// textual scan counts those lines as comments.
func countGoFile(path string) (v Volume, ok bool) {
	src, err := os.ReadFile(path)
	if err != nil {
		return
	}
	v.Files = 1
	total := strings.Count(string(src), "\n")
	if len(src) > 0 && !strings.HasSuffix(string(src), "\n") {
		total++
	}

	fset := token.NewFileSet()
	f := fset.AddFile(path, fset.Base(), len(src))
	var s scanner.Scanner
	// The error handler is a no-op: a file that does not parse still has
	// countable lines, and this is a tally, not a compiler.
	s.Init(f, src, func(token.Position, string) {}, scanner.ScanComments)

	code := make(map[int]struct{}, 256)
	comment := make(map[int]struct{}, 128)
	generated := false
	generator := ""
	for {
		pos, tok, lit := s.Scan()
		if tok == token.EOF {
			break
		}
		line := f.Position(pos).Line
		if tok == token.COMMENT {
			// A block comment covers every line it spans.
			for i := 0; i <= strings.Count(lit, "\n"); i++ {
				comment[line+i] = struct{}{}
			}
			if !generated {
				if g, isMarker := GeneratorOf(lit); isMarker {
					generated, generator = true, g
				}
			}
			continue
		}
		code[line] = struct{}{}
	}

	v.CodeLines = len(code)
	for l := range comment {
		if _, isCode := code[l]; !isCode {
			v.CommentLines++
		}
	}
	v.BlankLines = max(total-v.CodeLines-v.CommentLines, 0)
	if generated {
		v.GeneratedFiles = 1
		v.GeneratedCode = v.CodeLines
		v.Generators = []string{generator}
	}
	ok = true
	return
}

func countRawLines(path string) (n int, ok bool) {
	src, err := os.ReadFile(path)
	if err != nil {
		return
	}
	n = strings.Count(string(src), "\n")
	if len(src) > 0 && !strings.HasSuffix(string(src), "\n") {
		n++
	}
	ok = true
	return
}
