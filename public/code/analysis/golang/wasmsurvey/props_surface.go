package wasmsurvey

import (
	"bytes"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/stergiotis/boxer/public/observability/eh/eb"
	"github.com/stergiotis/boxer/public/packageprops"
)

// This file renders doc/SURFACE.md, the per-package statement of the
// compatibility promise (ADR-0389), from the harvested declarations. The
// output is a pure function of the declarations and the package doc comments
// — no timestamps — so `props surface --check` can require byte equality with
// the committed file.

// surfaceGroup is one section of the surface document.
type surfaceGroup struct {
	title string
	intro string
	keep  func(r HarvestRow) bool
}

// surfaceGroups lists the sections in document order. Every row lands in
// exactly one: a tiered package under its tier, an untiered one under its
// Kind, the rest under "Unclassified".
var surfaceGroups = []surfaceGroup{
	{
		title: "Stable",
		intro: "Covered by the compatibility promise in [VERSIONING.md](../VERSIONING.md): an incompatible change to the exported Go API is preceded by a deprecation window.",
		keep:  func(r HarvestRow) bool { return r.Stability == packageprops.StabilityStable },
	},
	{
		title: "Experimental",
		intro: "Public and usable, but may change in any MINOR version without a deprecation window.",
		keep:  func(r HarvestRow) bool { return r.Stability == packageprops.StabilityExperimental },
	},
	{
		title: "Internal",
		intro: "Implementation details that Go's import rules happen to expose. Not for use outside this module.",
		keep:  func(r HarvestRow) bool { return r.Stability == packageprops.StabilityInternal },
	},
	{
		title: "Test support",
		intro: "Helpers and conformance suites meant to be imported by tests. Outside the promise unless tiered above.",
		keep: func(r HarvestRow) bool {
			return r.Stability == packageprops.StabilityUnspecified &&
				(r.Kind == packageprops.KindTestSupport || r.Kind == packageprops.KindIntegrationTest)
		},
	},
	{
		title: "Tools",
		intro: "Command and governance packages of this repository's tooling. Their Go API is outside the promise; the `boxer` command tree they build is covered as described in VERSIONING.md.",
		keep: func(r HarvestRow) bool {
			return r.Stability == packageprops.StabilityUnspecified && r.Kind == packageprops.KindTool
		},
	},
	{
		title: "Demos and examples",
		intro: "Illustrative and demonstration code. Outside the promise.",
		keep: func(r HarvestRow) bool {
			return r.Stability == packageprops.StabilityUnspecified &&
				(r.Kind == packageprops.KindDemo || r.Kind == packageprops.KindExample)
		},
	},
	{
		title: "Unclassified",
		intro: "Packages that declare no tier. Outside the promise; an app package under `apps/` is here unless its declaration says otherwise.",
		keep: func(r HarvestRow) bool {
			return r.Stability == packageprops.StabilityUnspecified && r.Kind == packageprops.KindUnspecified
		},
	},
}

// surfaceArea is the heading a package is listed under within its group: the
// first path element below the module's public/ tree, or the top-level
// directory for anything outside it.
func surfaceArea(rel string) (area string) {
	parts := strings.Split(rel, "/")
	if parts[0] == "public" && len(parts) > 1 {
		return parts[1]
	}
	return parts[0]
}

// RenderSurface renders the surface document for rows (import paths under
// modPath). Packages without a declaration are not listed; the document says
// so in its opening.
func RenderSurface(rows []HarvestRow, modPath string) (src []byte) {
	var b bytes.Buffer
	b.WriteString(`---
type: reference
audience: consumer
status: draft
generated: true
generator: boxer code analysis golang wasmsurvey props surface
---

> **Status: draft — pre-human-review.** Generated from the ` + "`package_props.go`" + `
> declarations; regenerate with ` + "`boxer code analysis golang wasmsurvey props surface`" + `
> after changing a declaration. Review happens on the declarations and in
> [ADR-0389](./adr/0389-stability-tiers-per-package-and-what-a-version-number-promises.md).

# Package surface

<!-- Generated by ` + "`boxer code analysis golang wasmsurvey props surface`" + `. Do not edit by hand. -->

Each package of this module that carries a ` + "`package_props.go`" + ` declaration, by its
stability tier (ADR-0389), then by area. A package with no declaration is
outside the promise and is not listed. ` + "`public/packageprops`" + ` cannot declare
itself; ADR-0389 states its tier.

`)
	counts := make([]int, len(surfaceGroups))
	grouped := make([][]HarvestRow, len(surfaceGroups))
	for _, r := range rows {
		for gi, g := range surfaceGroups {
			if g.keep(r) {
				grouped[gi] = append(grouped[gi], r)
				counts[gi]++
				break
			}
		}
	}
	b.WriteString("| Section | Packages |\n| --- | ---: |\n")
	for gi, g := range surfaceGroups {
		fmt.Fprintf(&b, "| [%s](#%s) | %d |\n", g.title, surfaceAnchor(g.title), counts[gi])
	}
	for gi, g := range surfaceGroups {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n", g.title, g.intro)
		byArea := make(map[string][]HarvestRow)
		var areas []string
		for _, r := range grouped[gi] {
			rel := strings.TrimPrefix(r.ImportPath, modPath+"/")
			a := surfaceArea(rel)
			if _, ok := byArea[a]; !ok {
				areas = append(areas, a)
			}
			byArea[a] = append(byArea[a], r)
		}
		sort.Strings(areas)
		for _, a := range areas {
			fmt.Fprintf(&b, "\n### %s\n\n", a)
			list := byArea[a]
			sort.Slice(list, func(i, j int) bool { return list[i].ImportPath < list[j].ImportPath })
			for _, r := range list {
				rel := strings.TrimPrefix(r.ImportPath, modPath+"/")
				fmt.Fprintf(&b, "- `%s`", rel)
				if r.Kind != packageprops.KindUnspecified && r.Stability != packageprops.StabilityUnspecified {
					fmt.Fprintf(&b, " (%s)", r.Kind)
				}
				if r.Synopsis != "" {
					fmt.Fprintf(&b, " — %s", r.Synopsis)
				}
				b.WriteString("\n")
			}
		}
	}
	return b.Bytes()
}

// surfaceAnchor is the GitHub heading anchor for a section title.
func surfaceAnchor(title string) (anchor string) {
	return strings.ReplaceAll(strings.ToLower(title), " ", "-")
}

// WriteSurface renders the surface document and writes it to out, or with
// check set compares it to the committed file and fails on any difference.
func WriteSurface(rows []HarvestRow, modPath string, out string, check bool) (err error) {
	src := RenderSurface(rows, modPath)
	if check {
		var have []byte
		have, err = os.ReadFile(out)
		if err != nil {
			return eb.Build().Str("out", out).Errorf("props surface: read committed document: %w", err)
		}
		if !bytes.Equal(have, src) {
			return eb.Build().Str("out", out).Errorf("props surface: the committed document disagrees with the declarations; regenerate it with `props surface`")
		}
		return nil
	}
	if err = os.WriteFile(out, src, 0o644); err != nil {
		return eb.Build().Str("out", out).Errorf("props surface: write: %w", err)
	}
	return nil
}
